package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"unicode"

	gtfs "github.com/MobilityData/gtfs-realtime-bindings/golang/gtfs"
	"google.golang.org/protobuf/proto"
	"google.golang.org/protobuf/reflect/protodesc"
	"google.golang.org/protobuf/reflect/protoreflect"
)

func main() {
	output := flag.String("output", "projection_generated.go", "generated output path")
	flag.Parse()
	file := gtfs.File_gtfs_realtime_proto
	descriptorBytes, err := proto.MarshalOptions{Deterministic: true}.Marshal(protodesc.ToFileDescriptorProto(file))
	if err != nil {
		panic(err)
	}
	descriptorHash := sha256.Sum256(descriptorBytes)
	messages := flattenMessages(file.Messages())
	var b bytes.Buffer
	fmt.Fprintln(&b, "// Code generated by internal/projection/gen; DO NOT EDIT.")
	fmt.Fprintln(&b, "package projection")
	fmt.Fprintln(&b, `import "google.golang.org/protobuf/reflect/protoreflect"`)
	fmt.Fprintf(&b, "const DescriptorSHA256 = %q\n", hex.EncodeToString(descriptorHash[:]))
	for _, message := range messages {
		emitStruct(&b, message)
	}
	for _, message := range messages {
		emitMapper(&b, message)
	}
	formatted, err := format.Source(b.Bytes())
	if err != nil {
		_, _ = os.Stderr.Write(b.Bytes())
		panic(err)
	}
	target := *output
	if !filepath.IsAbs(target) && filepath.Base(filepath.Dir(target)) == "gen" {
		target = filepath.Join("..", target)
	}
	if err := os.WriteFile(target, formatted, 0o644); err != nil {
		panic(err)
	}
}

func flattenMessages(messages protoreflect.MessageDescriptors) []protoreflect.MessageDescriptor {
	var out []protoreflect.MessageDescriptor
	var visit func(protoreflect.MessageDescriptors)
	visit = func(items protoreflect.MessageDescriptors) {
		for i := 0; i < items.Len(); i++ {
			m := items.Get(i)
			if m.IsMapEntry() {
				continue
			}
			out = append(out, m)
			visit(m.Messages())
		}
	}
	visit(messages)
	sort.Slice(out, func(i, j int) bool { return string(out[i].FullName()) < string(out[j].FullName()) })
	return out
}

func emitStruct(b *bytes.Buffer, message protoreflect.MessageDescriptor) {
	fmt.Fprintf(b, "type %s struct {\n", typeName(message))
	fields := message.Fields()
	for i := 0; i < fields.Len(); i++ {
		field := fields.Get(i)
		fmt.Fprintf(b, "%s %s `parquet:\"%s\" json:\"%s,omitempty\"`\n",
			camel(string(field.Name())), fieldType(field), field.Name(), field.Name())
	}
	fmt.Fprintln(b, "}")
}

func emitMapper(b *bytes.Buffer, message protoreflect.MessageDescriptor) {
	name := typeName(message)
	fmt.Fprintf(b, "func project%s(m protoreflect.Message) *%s {\n", name, name)
	fmt.Fprintln(b, "if !m.IsValid() { return nil }")
	fmt.Fprintf(b, "out := &%s{}\n", name)
	fields := message.Fields()
	for i := 0; i < fields.Len(); i++ {
		emitField(b, fields.Get(i), i)
	}
	fmt.Fprintln(b, "return out")
	fmt.Fprintln(b, "}")
	if message.Name() == "FeedMessage" {
		fmt.Fprintf(b, "func ProjectFeedMessage(m protoreflect.Message) *%s { return project%s(m) }\n", name, name)
	}
}

func emitField(b *bytes.Buffer, field protoreflect.FieldDescriptor, index int) {
	goName := camel(string(field.Name()))
	fd := fmt.Sprintf("f%d", index)
	fmt.Fprintf(b, "%s := m.Descriptor().Fields().ByNumber(%d)\n", fd, field.Number())
	if field.IsList() {
		fmt.Fprintf(b, "if %s != nil { list := m.Get(%s).List(); if list.Len() > 0 { out.%s = make(%s, 0, list.Len()); for i := 0; i < list.Len(); i++ { ", fd, fd, goName, fieldType(field))
		if field.Kind() == protoreflect.MessageKind || field.Kind() == protoreflect.GroupKind {
			fmt.Fprintf(b, "out.%s = append(out.%s, project%s(list.Get(i).Message()))", goName, goName, typeName(field.Message()))
		} else {
			fmt.Fprintf(b, "out.%s = append(out.%s, %s)", goName, goName, valueExpr(field, "list.Get(i)"))
		}
		fmt.Fprintln(b, "} } }")
		return
	}
	fmt.Fprintf(b, "if %s != nil && m.Has(%s) { ", fd, fd)
	if field.Kind() == protoreflect.MessageKind || field.Kind() == protoreflect.GroupKind {
		fmt.Fprintf(b, "out.%s = project%s(m.Get(%s).Message())", goName, typeName(field.Message()), fd)
	} else if field.Kind() == protoreflect.BytesKind {
		fmt.Fprintf(b, "v := append([]byte(nil), m.Get(%s).Bytes()...); out.%s = &v", fd, goName)
	} else {
		fmt.Fprintf(b, "v := %s; out.%s = &v", valueExpr(field, "m.Get("+fd+")"), goName)
	}
	fmt.Fprintln(b, "}")
}

func fieldType(field protoreflect.FieldDescriptor) string {
	if field.Kind() == protoreflect.MessageKind || field.Kind() == protoreflect.GroupKind {
		base := "*" + typeName(field.Message())
		if field.IsList() {
			return "[]" + base
		}
		return base
	}
	base := scalarType(field)
	if field.IsList() {
		return "[]" + base
	}
	return "*" + base
}

func scalarType(field protoreflect.FieldDescriptor) string {
	switch field.Kind() {
	case protoreflect.BoolKind:
		return "bool"
	case protoreflect.EnumKind:
		return "int32"
	case protoreflect.Int32Kind, protoreflect.Sint32Kind, protoreflect.Sfixed32Kind:
		return "int32"
	case protoreflect.Uint32Kind, protoreflect.Fixed32Kind:
		return "uint32"
	case protoreflect.Int64Kind, protoreflect.Sint64Kind, protoreflect.Sfixed64Kind:
		return "int64"
	case protoreflect.Uint64Kind, protoreflect.Fixed64Kind:
		return "uint64"
	case protoreflect.FloatKind:
		return "float32"
	case protoreflect.DoubleKind:
		return "float64"
	case protoreflect.StringKind:
		return "string"
	case protoreflect.BytesKind:
		return "[]byte"
	default:
		panic(fmt.Sprintf("unsupported protobuf kind %s", field.Kind()))
	}
}

func valueExpr(field protoreflect.FieldDescriptor, value string) string {
	switch field.Kind() {
	case protoreflect.BoolKind:
		return value + ".Bool()"
	case protoreflect.EnumKind:
		return "int32(" + value + ".Enum())"
	case protoreflect.Int32Kind, protoreflect.Sint32Kind, protoreflect.Sfixed32Kind:
		return "int32(" + value + ".Int())"
	case protoreflect.Uint32Kind, protoreflect.Fixed32Kind:
		return "uint32(" + value + ".Uint())"
	case protoreflect.Int64Kind, protoreflect.Sint64Kind, protoreflect.Sfixed64Kind:
		return value + ".Int()"
	case protoreflect.Uint64Kind, protoreflect.Fixed64Kind:
		return value + ".Uint()"
	case protoreflect.FloatKind:
		return "float32(" + value + ".Float())"
	case protoreflect.DoubleKind:
		return value + ".Float()"
	case protoreflect.StringKind:
		return value + ".String()"
	case protoreflect.BytesKind:
		return "append([]byte(nil), " + value + ".Bytes()...)"
	default:
		panic(fmt.Sprintf("unsupported protobuf value kind %s", field.Kind()))
	}
}

func typeName(message protoreflect.MessageDescriptor) string {
	full := string(message.FullName())
	if dot := strings.IndexByte(full, '.'); dot >= 0 {
		full = full[dot+1:]
	}
	parts := strings.Split(full, ".")
	for i := range parts {
		parts[i] = camel(parts[i])
	}
	return strings.Join(parts, "_")
}

func camel(value string) string {
	var b strings.Builder
	upper := true
	for _, r := range value {
		if r == '_' || r == '-' || r == '.' {
			upper = true
			continue
		}
		if upper {
			r = unicode.ToUpper(r)
			upper = false
		}
		b.WriteRune(r)
	}
	return b.String()
}
